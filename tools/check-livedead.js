#!/usr/bin/env node
const fs = require("fs");
const path = require("path");
const Syllable = require("../js/syllable.js");

const input = process.argv[2];

function jsString(value) {
  return String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function countKey(map, key) {
  map[key] = (map[key] || 0) + 1;
}

function sortedKeys(obj) {
  return Object.keys(obj).sort();
}

function tableFromCounts(title, counts, flagRules) {
  const lines = ["", "### " + title, "", "| key | count | note |", "|---|---:|---|"];
  sortedKeys(counts).forEach((key) => {
    const note = flagRules && counts[key] < 12 ? "fewer than 12" : "";
    lines.push("| " + key + " | " + counts[key] + " | " + note + " |");
  });
  return lines;
}

function printCounts(title, counts, flagRules) {
  console.log(title + ":");
  sortedKeys(counts).forEach((key) => {
    const note = flagRules && counts[key] < 12 ? " (fewer than 12)" : "";
    console.log("  " + key + ": " + counts[key] + note);
  });
}

if (!input) {
  console.error("Usage: node tools/check-livedead.js <draft.json>");
  process.exit(0);
}

let draft;
try {
  draft = JSON.parse(fs.readFileSync(input, "utf8"));
} catch (err) {
  console.error("Could not read draft JSON: " + err.message);
  process.exit(0);
}

if (!Array.isArray(draft)) {
  console.error("Draft must be a JSON array.");
  process.exit(0);
}

const accepted = [];
const rejected = [];
const seen = Object.create(null);
const counts = {
  ruleKey: Object.create(null),
  toneKey: Object.create(null),
  category: Object.create(null),
  cls: Object.create(null)
};

draft.forEach((item) => {
  const a = Syllable.analyze(item.th);
  let reason = null;

  if (/[่-๋]/.test(item.th)) reason = "has tone mark";
  else if (!a) reason = "unparsed";
  else if (a.live !== item.live) reason = "live mismatch";
  else if (a.tone !== item.tone) reason = "tone mismatch";
  else if (seen[item.th]) reason = "duplicate";

  if (reason) {
    rejected.push({
      item,
      analysis: a,
      reason
    });
    return;
  }

  seen[item.th] = true;
  accepted.push({ th: item.th, rom: item.rom, en: item.en });
  countKey(counts.ruleKey, a.ruleKey);
  countKey(counts.toneKey, a.toneKey);
  countKey(counts.category, item.category || "");
  countKey(counts.cls, a.cls);
});

const dataLines = [
  "// js/livedead-data.js — generated by tools/check-livedead.js. Do not hand-edit;",
  "// edit the draft and re-run the gate. Live/dead and tone are computed at runtime",
  "// by Syllable.analyze, never stored.",
  "const LiveDeadData = (function () {",
  "  const words = ["
];

accepted.forEach((item, index) => {
  const comma = index === accepted.length - 1 ? "" : ",";
  dataLines.push(
    '    { th: "' + jsString(item.th) + '", rom: "' + jsString(item.rom) +
      '", en: "' + jsString(item.en) + '" }' + comma
  );
});

dataLines.push(
  "  ];",
  "  return { words };",
  "})();",
  "if (typeof module !== \"undefined\" && module.exports) module.exports = LiveDeadData;",
  ""
);

fs.writeFileSync(path.join(__dirname, "../js/livedead-data.js"), dataLines.join("\n"), "utf8");

const audit = [
  "# Live/Dead Audit",
  "",
  "| th | rom | en | category | draft live | draft tone | engine live | engine tone | reason |",
  "|---|---|---|---|---|---|---|---|---|"
];

rejected.forEach(({ item, analysis, reason }) => {
  audit.push(
    "| " + (item.th || "") +
      " | " + (item.rom || "") +
      " | " + (item.en || "") +
      " | " + (item.category || "") +
      " | " + String(item.live) +
      " | " + (item.tone || "") +
      " | " + (analysis ? String(analysis.live) : "") +
      " | " + (analysis ? analysis.tone : "") +
      " | " + reason + " |"
  );
});

audit.push(
  "",
  "## Summary",
  "",
  "Accepted: " + accepted.length,
  "",
  "Rejected: " + rejected.length
);
audit.push(...tableFromCounts("By ruleKey", counts.ruleKey, true));
audit.push(...tableFromCounts("By toneKey", counts.toneKey, false));
audit.push(...tableFromCounts("By category", counts.category, false));
audit.push(...tableFromCounts("By class", counts.cls, false));
audit.push("");

fs.writeFileSync(path.join(__dirname, "../AUDIT_LIVEDEAD.md"), audit.join("\n"), "utf8");

console.log("Accepted: " + accepted.length);
console.log("Rejected: " + rejected.length);
printCounts("By ruleKey", counts.ruleKey, true);
printCounts("By toneKey", counts.toneKey, false);
printCounts("By category", counts.category, false);
printCounts("By class", counts.cls, false);
process.exit(0);
